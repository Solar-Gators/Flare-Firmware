// should be 100 x 50
void drawCar()
{
    static constexpr uint32_t animation_dt = 60;
    static constexpr uint8_t max_offset = 2;
    static uint32_t last_animation_tick = 0;
    static int x_offset = 0;
    static int y_offset = 0;
    static bool increasing = true;

    uint32_t current_tick = HAL_GetTick();

    if (current_tick - last_animation_tick < animation_dt)
    {
        return;
    }

    if (increasing)
        y_offset++;
    else
        y_offset--;

    if (y_offset >= max_offset)
        increasing = false;
    if (y_offset <= 0)
        increasing = true;

    x_offset -= 3;

    if (x_offset < -245)
        x_offset = 0;

    for (int y = 0; y < 50; y++)
    {
        for (int x = 0; x < 100; x++)
        {
            int idx = (y * 100 + x) * 2;
            uint16_t color =
                (static_cast<uint16_t>(car[idx]) | static_cast<uint16_t>(car[idx + 1] << 8));
            if (color == 0)
                color = background_color;

            uint16_t x_loc = x + 315 + x_offset;

            if (x_loc < 170)
                continue;

            display.DrawPixel(x_loc, y + 185 + y_offset, color);
        }
    }
}
